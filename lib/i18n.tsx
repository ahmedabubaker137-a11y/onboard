interface I18nContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  isRtl: boolean;
  availableLanguages: LanguageMeta[];
}

const I18nContext = createContext<I18nContextType>({
  language: "en",
  setLanguage: () => {},
  t: (key) => key,
  isRtl: false,
  availableLanguages: SUPPORTED_LANGUAGES,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>("en");

  useEffect(() => {
    const saved = localStorage.getItem("onboardx_language") as LanguageCode | null;
    if (saved && TRANSLATIONS[saved]) {
      setLanguageState(saved);
      applyHtmlDir(saved);
    }
  }, []);

  const applyHtmlDir = (lang: LanguageCode) => {
    if (typeof document !== "undefined") {
      // Standard LTR layout kept intact as requested: language changes text, not layout direction
      document.documentElement.dir = "ltr";
      document.documentElement.lang = lang;
    }
  };

  const setLanguage = (newLang: LanguageCode) => {
    setLanguageState(newLang);
    if (typeof window !== "undefined") {
      localStorage.setItem("onboardx_language", newLang);
      applyHtmlDir(newLang);
    }
  };

  const t = (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (dict[key]) return dict[key];
    if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
    return fallback || key;
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        t,
        isRtl: false, // Keep consistent standard layout
        availableLanguages: SUPPORTED_LANGUAGES,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  return useContext(I18nContext);
}
